# 初期の固定Model 2 QR参照データを生成する。
# 現在の本番は動的符号化で、この生成データは比較・回帰確認用。
"""Generate the Phase 1 fixed QR reference data for regression tests.

The current QRTEST.EXE generates QR symbols dynamically and does not use
this fixed reference data.
"""

from pathlib import Path

import cv2
import numpy as np
import qrcode
from qrcode.constants import ERROR_CORRECT_Q
from qrcode.util import MODE_ALPHA_NUM, QRData

ROOT = Path(__file__).resolve().parents[1]
PAYLOAD = "PC98-QR-TEST-001"
VERSION = 1
MATRIX_SIZE = 21
QUIET_ZONE = 4
MODULE_SIZE = 12
MASK_PATTERN = 0  # Valid fixed mask; reproducible without automatic mask selection. / 日本語: 有効な固定マスクを使い、自動マスク選択に依存せず再現可能にする。


def make_qr():
    qr = qrcode.QRCode(
        version=VERSION,
        error_correction=ERROR_CORRECT_Q,
        box_size=MODULE_SIZE,
        border=0,  # The C matrix contains the symbol only, not its quiet zone. / 日本語: C行列にはQR本体だけを格納し、Quiet Zoneは含めない。
        mask_pattern=MASK_PATTERN,
    )
    qr.add_data(QRData(PAYLOAD, mode=MODE_ALPHA_NUM), optimize=0)
    qr.make(fit=False)  # Never silently increase the version. / 日本語: Versionを黙って引き上げない。
    matrix = qr.get_matrix()
    if qr.version != VERSION or len(matrix) != MATRIX_SIZE or any(
        len(row) != MATRIX_SIZE for row in matrix
    ):
        raise ValueError("Expected Version 1, exactly 21x21 modules")
    return qr


def render_header(matrix):
    rows = ["    {" + ", ".join(str(int(cell)) for cell in row) + "}," for row in matrix]
    return "\n".join([
        "/* Generated by tools/generate_fixed_qr.py; do not edit manually.",
        f" * {PAYLOAD}: Model 2, Version 1, Alphanumeric, ECC Q, mask {MASK_PATTERN}.",
        " * Quiet zone is supplied by the white screen, not stored here.",
        " */",
        "#ifndef PC98QR_FIXED_H",
        "#define PC98QR_FIXED_H",
        "",
        f"#define QR_MATRIX_SIZE {MATRIX_SIZE}",
        "",
        "static const unsigned char qr_matrix[QR_MATRIX_SIZE][QR_MATRIX_SIZE] = {",
        *rows,
        "};",
        "",
        "#endif",
        "",
    ])


def render_image(matrix):
    modules = np.pad(np.asarray(matrix, dtype=np.uint8), QUIET_ZONE)
    pixels = (1 - modules) * 255
    return pixels.repeat(MODULE_SIZE, axis=0).repeat(MODULE_SIZE, axis=1)


def main():
    qr = make_qr()
    matrix = qr.get_matrix()
    image = render_image(matrix)
    decoded, points, _ = cv2.QRCodeDetector().detectAndDecode(image)
    if points is None or decoded != PAYLOAD:
        raise RuntimeError(f"Generated QR failed decode: {decoded!r}")
    (ROOT / "src").mkdir(exist_ok=True)
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "src/qr_fixed.h").write_text(render_header(matrix), encoding="ascii")
    if not cv2.imwrite(str(ROOT / "build/fixed_qr.png"), image):
        raise OSError("Could not write build/fixed_qr.png")
    print(f"Model 2 / Version {qr.version} / ECC Q / Alphanumeric / 21x21 / mask {MASK_PATTERN}")
    print(f"348x348 pixels, 12 px/module, quiet zone 4; decoded: {decoded}")


if __name__ == "__main__":
    main()
